export type StringKey = keyof typeof STRINGS;

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[key][lang];
  // Each value in a first-strong isolate (FSI…PDI), so a phone number or
  // policy ref inside an Urdu sentence keeps its own left-to-right order.
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, `⁨${v}⁩`);
  return s;
}

/** `t("key", vars)` in the patient's chosen language, plus that language. */
export function useT() {
  const lang = useSession((s) => s.lang);
  return { lang, t: (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars) };
}

/** Pick the en/ur label off a seed option ({ en, ur }). */
export const pick = (o: { en: string; ur: string }, lang: Lang) => o[lang];
